"""Independent interface and route oracle for the four public tree examples."""
import re


def specification(mode):
    narrow = mode in ('apb16', 'axi64')
    bits = 16 if mode == 'apb16' else 64 if mode == 'axi64' else 32
    source = 'axi4_lite' if mode.startswith('axi') else 'apb4'
    target = 'axi4_lite' if mode == 'axi64' else 'apb4'
    paths = [['entry', 'control'], ['entry', 'leaf']] if narrow else [
        ['entry', 'control'], ['entry', 'branch', 'leaf'],
        ['entry', 'branch', 'leaf'], ['entry', 'control']]
    windows = [(0, 4096), (4096, 4096), (16384, 8192), (0xfffff000, 4096)][:len(paths)]
    return bits, source, target, paths, windows


def check(mapping, bundle, rtl, mode, version):
    bits, source, target, paths, windows = specification(mode)
    d, n = mapping['definition'], mapping['network']
    module = 'nocloom_control_tree_' + mode
    assert mapping['module'] == bundle['top'] == module, 'MODULE'
    assert mapping['generator'] == bundle['generator'] == 'NocLoom', 'GENERATOR'
    assert bundle['version'] == version and 'version' not in mapping, 'VERSION'
    assert rtl.startswith('// Generated by NocLoom\n// SPDX-License-Identifier: '), 'HEADER'
    assert d['address_width'] == 32 and d['domain'] == 'main', 'DOMAIN_ADDRESS'
    assert d['initiators'] == ['cpu', 'dma'], 'SOURCES'
    assert d['targets'] == [dict(name=f'bank{i:02}', begin=str(b), end=str(b+s))
                            for i, (b, s) in enumerate(windows)], 'WINDOWS'
    pairs = [dict(source=s, target=f'bank{i:02}') for s in ('cpu','dma') for i in range(len(paths))]
    assert d['connectivity'] == pairs, 'CONNECTIVITY'
    assert d['endpoint_protocols'] == dict(initiators={s:source for s in ('cpu','dma')},
                                         targets={f'bank{i:02}':target for i in range(len(paths))}), 'PROTOCOLS'
    for direction in ('request', 'response'):
        graph = d['topology'][direction]
        names = sorted(set(sum(paths, [])))
        assert [x['name'] for x in graph['nodes']] == names, 'NODES'
        edges = set((a,b) for path in paths for a,b in zip(path,path[1:]))
        if direction == 'response': edges = {(b,a) for a,b in edges}
        assert graph['links'] == [dict(zip(('from','to'),e)) for e in sorted(edges)], 'LINKS'
        roots = [dict(endpoint=s,node='entry') for s in ('cpu','dma')]
        owners = [dict(endpoint=f'bank{i:02}',node=p[-1]) for i,p in enumerate(paths)]
        assert graph['entries'] == (roots if direction=='request' else owners), 'ENTRIES'
        assert graph['exits'] == (owners if direction=='request' else roots), 'EXITS'
        hardware = {x['name']:x['hardware_node'] for x in graph['nodes']}
        expected = []
        for s in ('cpu','dma'):
            for i,path in enumerate(paths):
                route = path if direction=='request' else path[::-1]
                expected.append(dict(entry=s if direction=='request' else f'bank{i:02}',
                                     exit=f'bank{i:02}' if direction=='request' else s,
                                     hardware_nodes=[hardware[x] for x in route]))
        assert n[direction+'_routes'] == sorted(expected,key=lambda x:(x['entry'],x['exit'])), 'ROUTES'
    assert n['read_write'] == 'merged', 'DIRECTIONS'
    assert n['storage'] and all(x['acquire'] and x['release'] for x in n['storage']), 'STORAGE_BINDINGS'
    resources={x['name'] for x in n['resources']}
    assert all(x['resource'] in resources for x in n['storage']), 'RESOURCE_BINDINGS'
    ports = mapping['ports']
    assert len({p['name'] for p in ports}) == len(ports), 'PORT_UNIQUE'
    for p in ports:
        # Reset and test ports have no owning clock.
        assert p['clock']==('' if p['signal'] in ('reset_n','test') else 'clk_main') and p['width']>0, 'PORT_CLOCK_WIDTH'
        match = re.search(r'\b'+p['direction']+r'\s+(?:wire\s+)?(?:\[(\d+):0\]\s+)?'+re.escape(p['name'])+r'\b',rtl)
        assert match and (int(match.group(1))+1 if match.group(1) else 1)==p['width'], 'RTL_PORT'
        if p['signal'] in ('pwdata','prdata','wdata','rdata'):assert p['width']==bits, 'DATA_WIDTH'
        if p['signal'] in ('pstrb','wstrb'):assert p['width']==bits//8, 'MASK_WIDTH'
    files={x['path']:x['role'] for x in bundle['files']}
    assert files=={module+'.v':'rtl',module+'.map.json':'interface_map',module+'.dependency.json':'dependency_graph',module+'.bundle.json':'manifest',
                   'nocloom_clock_gate.v':'cell_model','nocloom_synchronizer.v':'cell_model'}, 'ARTIFACT_COMPLETE'
    c=d['contract']
    assert c['address_transform']=='target_local_byte_offset_once', 'ADDRESS_TRANSFORM'
    assert c['write_data_unstrobed_bytes']=='zero_at_every_target_cleared_at_source_capture', 'INACTIVE_DATA'
    assert c['reset']=='common_cancel_all_initiators_network_targets', 'RESET'
    assert c['arbitration']['default']=='round_robin', 'ARBITRATION'
