"""Random-backpressure stress bench for the AXI4 width converters and the
bounded packet splitter, through networks generated by the public CLI.

Sources and target t0 drive and accept every channel with random valid and
ready (per-segment rates of 10 to 100 percent, every fourth segment at full
rate; W may lead AW at the target). Bursts are INCR, WRAP and FIXED, narrow or
full width, aligned or not, 1 to 64 beats, AxCACHE 0, 2 or 3, random IDs, with
full, sparse, half or empty strobes (unstrobed bytes carry garbage). Address
classes: target error page (SLVERR, no store), unrouted (an error from the default target)
and, with --exclusive, admitted exclusive bursts (target mode, EXOKAY). A
FIXED burst wider than t0 is refused by the width converter (SLVERR, no
target access, zero read data). About
one segment in three takes a common reset at a random cycle.

The mo_* modes give sources shared read/write burst capacity (MULTI) next to
per-target widths: up to six bursts per source and direction are generated
ahead, writes to six disjoint 2 KiB slots (error page: 256-byte slots), and a
B or an R beat must belong to the oldest open burst of its AXI ID, which
counts its own beats: R beats of different IDs may interleave. Bursts of other
IDs may complete earlier (a burst to the other target, a decode miss answered there,
overtakes a burst to t0): the bench counts such overtakes and the most bursts
in flight at each source face.

Checks: valid and payload held until the handshake on every target request
and source response channel; WLAST and strobe lanes at the target; every
strobed byte reaches the target exactly once with the source's value and
every unstrobed byte is zero; a B only after all the burst's bytes arrived
(a rejected burst delivers none); response codes per class and zero data on
error beats; an exclusive burst is one target burst; target memory and read
data against the model at each segment end; outputs idle in reset; no hang.

configuration(mode, exclusive) gives the YAML definition and bench(mode,
mapping, exclusive) the test bench text.
"""
