"""Exercise the output arbiter library alone against its cycle-accurate policy model.

dynamic: every configuration is generated by the fixture, simulated with a
reactive valid/ready bench (requests never retract, packets may pause
between fragments) and the logged cycles are replayed through
treadle_model.Arbiter; every cycle must match. Saturation phases also check
the waiting bound (fair policies) and starvation (fixed priority). Rotating
priority packet cases add a directed episode that must reach the bound.
Outputs of every size use the same global arbiter model.

formal: the generated arbiter is extended with environment assumptions and
safety properties (one transfer per cycle, grant held through stalls and
packets, work conservation, waiting bound for the fair policies, rank order
for fixed priority, the tree order of a release counter for rotating
priority; for FIFO arrival order, same-cycle ties highest index first and the
released winner queued last) and proved with SymbiYosys. Controls
check each property family against an arbiter that must violate it. A proof
that does not pass is rerun as a bounded check to name the violated property;
every case is evaluated before the result is reported.

--prepare writes every case without running a tool; --check evaluates the
logs a separate run left in the same work directory.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
import sim_process
from cross_hardware_sim import simulate
from treadle_model import Arbiter, tree_order

POLICIES = ("round_robin", "rotating_priority", "fixed_priority", "fifo")
FAIR = ("round_robin", "rotating_priority", "fifo")


def bound(case, policy=None):
    """Packets released to others while one head waits.

    Round robin and FIFO: n - 1. Rotating priority: 2^ceil(log2 n), the
    counter period. A deepest tree leaf comes first at exactly one counter
    value; a head that arrives there while another candidate holds the grant
    is passed by that release and then by every other counter value.
    """
    policy = policy or case["policy"]
    n = case["count"]
    return 1 << (n - 1).bit_length() if policy == "rotating_priority" else n - 1


CYCLES = 6000


def ranks(count):
    """A fixed non-identity permutation: odd indexes first, then even ones."""
    order = [i for i in range(count) if i % 2] + [i for i in range(count) if not i % 2]
    rank = [0] * count
    for r, i in enumerate(order):
        rank[i] = r
    return rank


def cases(kind):
    rows = []
    sizes = (2, 3, 4, 5, 8, 9, 16) if kind == "dynamic" else (2, 3, 4, 5)
    for policy in POLICIES:
        for n in sizes:
            rows.append(("output", policy, n, True))
    if kind == "dynamic":
        # Boundary and large outputs use the same global policy.
        rows += [("output", policy, n, True) for policy in FAIR for n in (17, 21, 32)]
        rows += [("output", "fixed_priority", n, True) for n in (5, 17, 32)]
    if kind == "formal":
        rows.append(("output", "fifo", 8, True))
    result = []
    for layout, policy, n, packet in rows:
        name = f"{layout}-{policy}-{n}-{'packet' if packet else 'message'}"
        result.append(dict(name=name, layout=layout, policy=policy, count=n, packet=packet,
                           rank=ranks(n) if policy == "fixed_priority" else None, claim=policy))
    if kind == "formal":
        # Controls: each property family checked against an arbiter that must
        # violate it, so a vacuous environment or property cannot pass.
        # A control may restrict the claim to one property family.
        for policy, claim, n, expect, family in [
                ("fixed_priority", "round_robin", 3, "nl_f_bound_", None),
                ("rotating_priority", "round_robin", 3, "nl_f_bound_", None),
                ("round_robin", "rotating_priority", 3, "nl_f_tree_", None),
                ("round_robin", "rotating_priority", 4, "nl_f_tree_", None),
                ("round_robin", "fifo", 3, "nl_f_order_", "order"),
                ("round_robin", "fifo", 3, "nl_f_tie_", "tie"),
                ("fixed_priority", "fifo", 3, "nl_f_back_", "back"),
                ("round_robin", "fixed_priority", 3, "nl_f_rank_", None),
                ("fifo", "fixed_priority", 3, "nl_f_rank_", None)]:
            suffix = f"-{family}" if family else ""
            result.append(dict(name=f"control-{policy}-as-{claim}{suffix}-{n}", layout="output",
                               policy=policy, count=n, packet=True, rank=ranks(n),
                               claim=claim, control=expect, family=family))
    return result


def generate(fixture, case, folder):
    argv = [fixture, str(folder), case["layout"], case["policy"], str(case["count"]),
            "packet" if case["packet"] else "message"]
    if case["policy"] == "fixed_priority":
        argv.append(",".join(map(str, case["rank"])))
    subprocess.run(argv, check=True, timeout=120)


def worst_case(case):
    """Directed rotating episode reaching the bound: (candidate, arrival cycle).

    A candidate that comes first at exactly one counter value v (a deepest
    tree leaf) stays idle while every other candidate requests two-fragment
    packets back to back, so decision k is taken at cycle 2k with counter k.
    It arrives at cycle 2v + 1, while the packet granted at value v is held,
    and is then passed by that release and by every other counter value.
    """
    n = case["count"]
    period = 1 << (n - 1).bit_length()
    firsts = [tree_order(0, n, p)[0] for p in range(period)]
    c = next(i for i in range(n) if firsts.count(i) == 1)
    return c, 2 * firsts.index(c) + 1


def bench(case, seed, directed=None):
    """Reactive valid/ready bench. A fragment stays presented until it moves;
    the move is latched in the cycle it happens (before the clock edge), so
    requests never retract. directed = (candidate, arrival): every other
    candidate requests two-fragment packets back to back with the receiver
    always ready, the candidate requests one packet from the arrival cycle."""
    n, packet = case["count"], case["packet"]
    bits = max(1, (n - 1).bit_length())
    lasts = "".join(f",.nl_last{i}(last[{i}])" for i in range(n)) if packet else ""
    ports = (".nl_clk(clk),.nl_reset_n(reset_n),.nl_ready(ready)"
             + "".join(f",.nl_valid{i}(valid[{i}])" for i in range(n)) + lasts
             + "".join(f",.nl_taken{i}(taken[{i}])" for i in range(n))
             + ",.nl_sink_valid(sink_valid),.nl_sink_payload(payload),.nl_winner(winner)"
             + ",.nl_held(held),.nl_transfer(transfer),.nl_release(released)")
    # Phases: 0 random load, 1 saturation (every candidate always requests,
    # receiver always ready), 2 saturation with receiver stalls, 3 sparse.
    if directed:
        target, start = directed
        cycles = start + 2 * (1 << (n - 1).bit_length()) + 8
        phase, length = "1", "2"
        arrival = f"(i != {target} || (cycle >= {start} && !served))"
    else:
        target, cycles, phase = -1, CYCLES, f"cycle * 4 / {CYCLES}"
        arrival, length = "chance(arrive)", "1 + ($unsigned($random(seed)) % longest)"
    return f"""`timescale 1ns/1ps
module tb;
reg clk = 0, reset_n = 0, ready = 0;
reg [{n-1}:0] valid = 0, last = 0, moved = 0;
wire [{n-1}:0] taken;
wire sink_valid, held, transfer, released;
wire [{bits-1}:0] payload, winner;
integer remaining [0:{n-1}];
integer i, cycle, phase, seed, arrive, pause, readiness, longest, cycles, served;
always #5 clk = ~clk;
nocloom_arbiter dut({ports});
function integer chance(input integer percent);
  chance = ($unsigned($random(seed)) % 100) < percent;
endfunction
initial begin
  seed = {seed};
  served = 0;
  cycles = {cycles};
  for (i = 0; i < {n}; i = i + 1) remaining[i] = 0;
  repeat (3) @(negedge clk);
  reset_n = 1;
  for (cycle = 0; cycle < cycles; cycle = cycle + 1) begin
    phase = {phase};
    arrive = phase == 0 ? 35 : phase == 3 ? 8 : 100;
    pause = phase == 0 ? 25 : phase == 3 ? 40 : 0;
    readiness = phase == 0 ? 70 : phase == 1 ? 100 : phase == 2 ? 55 : 80;
    longest = {4 if packet else 1};
    for (i = 0; i < {n}; i = i + 1) begin
      if (moved[i]) begin
        remaining[i] = remaining[i] - 1;
        valid[i] = 0;
        if (i == {target} && remaining[i] == 0) served = 1;
      end
      if (!valid[i]) begin
        if (remaining[i] == 0 && {arrival})
          remaining[i] = {length};
        if (remaining[i] > 0 && !chance(pause))
          valid[i] = 1;
      end
      last[i] = remaining[i] == 1;
    end
    ready = chance(readiness);
    #2;
    $display("C %0d %0d %b %b %0d %0d %0d %0d %0d %0d %0d %b", cycle, phase, valid, last, ready,
             sink_valid, payload, winner, held, transfer, released, taken);
    moved = valid & taken;
    @(negedge clk);
  end
  $display("ARBITER_PASS");
  $finish;
end
endmodule
"""


def check(case, log, flat=False):
    n = case["count"]
    model = Arbiter(case["policy"], n, case["packet"], case["rank"])
    mismatches, rows = [], 0
    served = [[0] * n for _ in range(4)]
    waiting = [0] * n
    worst = [0] * 4
    for line in log.splitlines():
        if not line.startswith("C "):
            continue
        part = line.split()
        cycle, phase = int(part[1]), int(part[2])
        valid = [part[3][n - 1 - i] == "1" for i in range(n)]
        last = [part[4][n - 1 - i] == "1" for i in range(n)]
        ready = part[5] == "1"
        sink_valid, payload, winner, held = (int(x) for x in part[6:10])
        transfer, release = int(part[10]), int(part[11])
        taken = [part[12][n - 1 - i] == "1" for i in range(n)]
        want = model.step(valid, last if case["packet"] else [True] * n, ready)
        got = dict(sink_valid=bool(sink_valid), held=bool(held), transfer=bool(transfer),
                   release=bool(release))
        expected = {k: want[k] for k in got}
        if want["sink_valid"] or want["held"]:
            got["winner"], expected["winner"] = winner, want["winner"]
        if want["sink_valid"]:
            got["payload"], expected["payload"] = payload, want["winner"]
        moved = [valid[i] and taken[i] for i in range(n)]
        got["moved"] = moved
        expected["moved"] = [want["transfer"] and want["winner"] == i for i in range(n)]
        if got != expected and len(mismatches) < 20:
            mismatches.append(dict(cycle=cycle, inputs=part[3:6], got=got, expected=expected))
        # Waiting bound: packets released to others while a head waits.
        for i in range(n):
            if moved[i] or not valid[i]:
                waiting[i] = 0
            elif release and winner != i:
                waiting[i] += 1
                worst[phase] = max(worst[phase], waiting[i])
            if moved[i] and (not case["packet"] or last[i]):
                served[phase][i] += 1
        rows += 1
    stats = dict(rows=rows, worst_wait=worst, served=served)
    return mismatches, stats


def verdict(case, log, mismatches, stats):
    n = case["count"]
    assert "ARBITER_PASS" in log and stats["rows"] == CYCLES, (case["name"], log[-400:])
    assert not mismatches, (case["name"], json.dumps(mismatches[:3], indent=1))
    # Phase 2 follows a whole saturated phase, so no grant from the random
    # phase is still held there.
    saturated = stats["served"][2]
    if case["policy"] in FAIR:
        assert max(stats["worst_wait"]) <= bound(case), (case["name"], stats)
        # Under saturation every candidate is served.
        assert min(saturated) > 0, (case["name"], stats)
    else:
        lowest = case["rank"].index(n - 1)
        # Fixed priority starves the lowest rank while all others saturate.
        assert saturated[lowest] == 0 and sum(saturated) > 0, (case["name"], stats)
    # The bench must actually reach contention and packet holds.
    assert stats["worst_wait"][1] >= (n - 1 if case["policy"] in FAIR else 0), stats


def verdict_worst(case, log, mismatches, stats):
    """The directed rotating episode reaches the bound exactly (it is tight)."""
    assert "ARBITER_PASS" in log, (case["name"], "worst", log[-400:])
    assert not mismatches, (case["name"], "worst", json.dumps(mismatches[:3], indent=1))
    assert max(stats["worst_wait"]) == bound(case), (case["name"], "worst", stats)


def formal(case, rtl):
    n, packet, claim = case["count"], case["packet"], case["claim"]
    only = case.get("family")
    width = max(2, n.bit_length() + 1)
    lines = ["reg nl_f_past = 0, nl_f_was_running = 0;",
             "always @(posedge nl_clk) begin nl_f_past <= 1; nl_f_was_running <= nl_reset_n; "
             "if (!nl_f_past) assume(!nl_reset_n); end",
             "wire nl_f_on = nl_f_past && nl_reset_n && nl_f_was_running;"]
    move = [f"(nl_valid{i} && nl_taken{i})" for i in range(n)]
    lines.append(f"wire [{n-1}:0] nl_f_move = {{{', '.join(reversed(move))}}};")
    body = []
    for i in range(n):
        stay = f"nl_valid{i}" + (f" && nl_last{i} == $past(nl_last{i})" if packet else "")
        # A presented fragment stays presented, unchanged, until it moves.
        body.append(f"if (nl_f_on && $past(nl_valid{i} && !nl_taken{i})) assume({stay});")
    body.append("if (nl_f_on) nl_f_one: assert((nl_f_move & (nl_f_move - 1)) == 0);")
    for i in range(n):
        body.append(f"if (nl_f_on && nl_f_move[{i}]) nl_f_mover_{i}: assert(nl_winner == {i});")
    body.append("if (nl_f_on && $past(nl_sink_valid && !nl_ready)) "
                "nl_f_stall: assert(nl_winner == $past(nl_winner));")
    if packet:
        body.append("if (nl_f_on && $past(nl_transfer && !nl_release)) "
                    "nl_f_packet: assert(nl_winner == $past(nl_winner) && nl_held);")
    any_valid = " || ".join(f"nl_valid{i}" for i in range(n))
    body.append(f"if (nl_f_on && !nl_held && ({any_valid})) nl_f_work: assert(nl_sink_valid);")
    if claim in FAIR:
        limit = bound(case, claim) + 1
        for i in range(n):
            c = f"nl_f_bypass{i}"
            lines.append(f"reg [{width-1}:0] {c} = 0;")
            body.append(f"if (!nl_reset_n || !nl_valid{i} || nl_f_move[{i}]) {c} <= 0; "
                        f"else if (nl_release && nl_winner != {i} && {c} < {limit}) {c} <= {c} + 1;")
            body.append(f"if (nl_f_on) nl_f_bound_{i}: assert({c} < {limit});")
    if claim == "rotating_priority":
        # A release counter of ceil(log2 n) bits, wrapping at its width; the
        # unheld choice is the first valid candidate in its tree order.
        w = (n - 1).bit_length()
        lines.append(f"reg [{w-1}:0] nl_f_count = 0;")
        body.append("if (!nl_reset_n) nl_f_count <= 0; else if (nl_release) nl_f_count <= nl_f_count + 1;")
        for p in range(1 << w):
            order = tree_order(0, n, p)
            for k, c in enumerate(order):
                ahead = "".join(f" && !nl_valid{x}" for x in order[:k])
                body.append(f"if (nl_f_on && !nl_held && nl_f_count == {p} && nl_valid{c}{ahead}) "
                            f"nl_f_tree_{p}_{c}: assert(nl_winner == {c});")
    if claim == "fixed_priority":
        rank = case["rank"]
        for w in range(n):
            for j in range(n):
                if rank[j] < rank[w]:
                    body.append(f"if (nl_f_on && !nl_held && nl_sink_valid && nl_winner == {w}) "
                                f"nl_f_rank_{w}_{j}: assert(!nl_valid{j});")
    if claim == "fifo" and only in (None, "order"):
        for i in range(n):
            lines.append(f"reg nl_f_packet{i} = 0, nl_f_wait{i} = 0;")
            lines.append(f"wire nl_f_head{i} = nl_valid{i} && !nl_f_packet{i};")
            lines.append(f"wire nl_f_arrive{i} = nl_f_head{i} && !nl_f_wait{i};")
            tail = f"nl_last{i}" if packet else "1'b1"
            body.append(f"if (!nl_reset_n) begin nl_f_packet{i} <= 0; nl_f_wait{i} <= 0; end else begin "
                        f"if (nl_f_move[{i}]) nl_f_packet{i} <= !{tail}; "
                        f"nl_f_wait{i} <= nl_f_head{i} && !nl_f_move[{i}]; end")
        for i in range(n):
            for j in range(n):
                if i == j:
                    continue
                o = f"nl_f_older{i}_{j}"
                lines.append(f"reg {o} = 0;")
                body.append(f"if (!nl_reset_n || nl_f_move[{i}] || nl_f_move[{j}]) {o} <= 0; "
                            f"else if (nl_f_arrive{j} && nl_f_wait{i} && nl_f_head{i}) {o} <= 1;")
                # Older: i already waited when j arrived (this cycle or before).
                body.append(f"if (nl_f_on && !nl_held && nl_sink_valid && nl_winner == {j} && "
                            f"nl_f_head{i} && ({o} || (nl_f_arrive{j} && nl_f_wait{i}))) "
                            f"nl_f_order_{i}_{j}: assert(0);")
    if claim == "fifo" and only in (None, "tie"):
        # Same-cycle arrivals keep the reset order, highest index first, while
        # neither has been served since reset.
        for i in range(n):
            lines.append(f"reg nl_f_served{i} = 0, nl_f_was{i} = 0;")
            lines.append(f"wire nl_f_new{i} = nl_valid{i} && !nl_f_was{i};")
            body.append(f"if (!nl_reset_n) begin nl_f_served{i} <= 0; nl_f_was{i} <= 0; end else begin "
                        f"nl_f_was{i} <= nl_valid{i}; if (nl_f_move[{i}]) nl_f_served{i} <= 1; end")
        for i in range(n):
            for j in range(i + 1, n):
                t = f"nl_f_twin{i}_{j}"
                fresh = f"!nl_f_served{i} && !nl_f_served{j}"
                lines.append(f"reg {t} = 0;")
                body.append(f"if (!nl_reset_n) {t} <= 0; "
                            f"else if (nl_f_new{i} && nl_f_new{j} && {fresh}) {t} <= 1;")
                body.append(f"if (nl_f_on && !nl_held && nl_sink_valid && nl_winner == {i} && "
                            f"nl_valid{j} && {fresh} && ({t} || (nl_f_new{i} && nl_f_new{j}))) "
                            f"nl_f_tie_{i}_{j}: assert(0);")
    if claim == "fifo" and only in (None, "back"):
        # The released winner queues behind every other request.
        lines.append(f"reg nl_f_released = 0; reg [{width-1}:0] nl_f_last_winner = 0;")
        body.append("if (!nl_reset_n) nl_f_released <= 0; "
                    "else begin nl_f_released <= nl_release; nl_f_last_winner <= nl_winner; end")
        for j in range(n):
            others = " || ".join(f"nl_valid{k}" for k in range(n) if k != j)
            body.append(f"if (nl_f_on && nl_f_released && nl_f_last_winner == {j} && !nl_held && "
                        f"({others})) nl_f_back_{j}: assert(nl_winner != {j});")
    block = "\n".join(lines) + "\nalways @(posedge nl_clk) begin\n" + "\n".join(body) + "\nend\n"
    return rtl.replace("endmodule", block + "endmodule")


def sby(depth, control=False):
    if control:
        return (f"[options]\nmode bmc\ndepth {depth}\n[engines]\nsmtbmc z3\n"
                "[script]\nread -formal network.v\nprep -top nocloom_arbiter\n[files]\nnetwork.v\n")
    return (f"[options]\nmode prove\ndepth {depth}\n[engines]\nabc pdr\n"
            "[script]\nread -formal network.v\nprep -top nocloom_arbiter\n[files]\nnetwork.v\n")


def prepare(args, work):
    rows = []
    for index, case in enumerate(cases(args.case)):
        folder = work / case["name"]
        if folder.exists():
            assert not folder.is_symlink()
            assert folder.resolve() != work.resolve() and folder.resolve().is_relative_to(work.resolve())
            shutil.rmtree(folder)
        generate(args.fixture, case, folder)
        rtl = (folder / "network.v").read_text()
        if args.case == "dynamic":
            case["seed"] = args.seed + index
            (folder / "tb.sv").write_text(bench(case, case["seed"]))
            if case["policy"] == "rotating_priority" and case["packet"]:
                (folder / "worst").mkdir()
                shutil.copy(folder / "network.v", folder / "worst" / "network.v")
                (folder / "worst" / "tb.sv").write_text(
                    bench(case, case["seed"], worst_case(case)))
        else:
            (folder / "network.v").write_text(formal(case, rtl))
            (folder / "task.sby").write_text(sby(4 * case["count"] + 8, case.get("control")))
        (folder / "case.json").write_text(json.dumps(case) + "\n")
        rows.append(case["name"])
    (work / "cases.json").write_text(json.dumps(rows, indent=1) + "\n")
    return rows


def run(args, work, names):
    for name in names:
        folder = work / name
        if args.case == "dynamic":
            for f in (folder, folder / "worst"):
                if (f / "tb.sv").exists():
                    rc = simulate(f, work / "compiled")
                    (f / "rc.txt").write_text(f"{rc}\n")
        else:
            # The FIFO proof at eight candidates is the largest task and has
            # the longer timeout.
            r = sim_process.run(["sby", "-f", "task.sby"], cwd=folder, capture_output=True,
                                text=True, timeout=5400 if "fifo-8" in name else 1800)
            (folder / "sby.log").write_text(r.stdout + r.stderr)
            status = folder / "task" / "status"
            if not case_of(folder).get("control") and not (
                    status.exists() and status.read_text().startswith("PASS")):
                # Name the violated property: a bounded run of the same depth
                # writes its trace through the SMT engine.
                (folder / "bmc.sby").write_text(sby(4 * case_of(folder)["count"] + 8, True))
                r = sim_process.run(["sby", "-f", "bmc.sby"], cwd=folder, capture_output=True,
                                    text=True, timeout=1800)
                (folder / "bmc.log").write_text(r.stdout + r.stderr)


def case_of(folder):
    return json.loads((folder / "case.json").read_text())


def failed_property(log):
    lines = [line for line in log.splitlines() if "Assert failed in" in line]
    return lines[0].split()[-1] if lines else None


def evaluate(args, work, names):
    report, failures = [], []
    for name in names:
        folder = work / name
        case = json.loads((folder / "case.json").read_text())
        if args.case == "dynamic":
            log = (folder / "simulation.log").read_text()
            rc = (folder / "rc.txt").read_text().strip()
            assert rc == "0", (name, "simulation exit", rc)
            mismatches, stats = check(case, log)
            verdict(case, log, mismatches, stats)
            row = dict(name=name, **stats)
            if (folder / "worst" / "tb.sv").exists():
                worst = folder / "worst"
                rc = (worst / "rc.txt").read_text().strip()
                assert rc == "0", (name, "worst simulation exit", rc)
                log = (worst / "simulation.log").read_text()
                mismatches, stats = check(case, log)
                verdict_worst(case, log, mismatches, stats)
                row["directed_worst_wait"] = max(stats["worst_wait"])
            report.append(row)
        else:
            path = folder / "task" / "status"
            status = path.read_text().split() if path.exists() else ["MISSING"]
            want = "FAIL" if case.get("control") else "PASS"
            if case.get("control"):
                case["failed"] = failed_property((folder / "sby.log").read_text())
                if status[0] != want or not case["failed"] or \
                        not case["failed"].startswith(case["control"]):
                    failures.append((name, status, case["failed"]))
            elif status[0] != want:
                # Every non-passing proof is reported with the property its
                # bounded rerun violates (the prove engine may fail to write a
                # trace and end in ERROR although it found a counterexample).
                bmc = folder / "bmc.log"
                case["failed"] = failed_property(bmc.read_text()) if bmc.exists() else None
                failures.append((name, status, case["failed"]))
            report.append(dict(name=name, status=status[0], failed=case.get("failed")))
    (work / "report.json").write_text(json.dumps(report, indent=1) + "\n")
    assert not failures, failures
    print(f"ARBITER_LIBRARY_PASS {args.case} cases={len(report)}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--fixture")
    p.add_argument("--work", required=True)
    p.add_argument("--case", choices=("dynamic", "formal"), required=True)
    p.add_argument("--seed", type=int, default=20261001)
    stage = p.add_mutually_exclusive_group()
    stage.add_argument("--prepare", action="store_true")
    stage.add_argument("--check", action="store_true")
    args = p.parse_args()
    work = Path(args.work).resolve()
    work.mkdir(parents=True, exist_ok=True)
    if args.check:
        names = json.loads((work / "cases.json").read_text())
    else:
        names = prepare(args, work)
        if args.prepare:
            return
        run(args, work, names)
    evaluate(args, work, names)


if __name__ == "__main__":
    main()
