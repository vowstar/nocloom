"""Check every endpoint pair and explicit route in public scale artifacts."""

import re


def verify(mapping, bundle, rtl, config, version):
    sources = sorted(x["name"] for x in config["initiators"])
    targets = sorted(x["name"] for x in config["targets"])
    d = mapping["definition"]
    n = mapping["network"]
    module = "nocloom_" + config["name"]
    assert (
        mapping["module"] == bundle["top"] == module
        and mapping["generator"] == bundle["generator"] == "NocLoom"
        and bundle["version"] == version
        and "version" not in mapping
        and rtl.startswith("// Generated by NocLoom\n// SPDX-License-Identifier: ")
    ), "PUBLIC_IDENTITY"
    assert (
        d["initiators"] == sources and sorted(x["name"] for x in d["targets"]) == targets
    ), "ENDPOINTS"
    expected = [
        dict(
            name=t["name"],
            begin=str(int(t["mappings"][0]["base"], 0)),
            end=str(int(t["mappings"][0]["base"], 0) + int(t["mappings"][0]["size"], 0)),
        )
        for t in config["targets"]
    ]
    assert d["targets"] == expected, "WINDOWS"
    assert d["connectivity"] == [
        dict(source=s, target=t) for s in sources for t in targets
    ], "CONNECTIVITY"
    used = set()
    for direction in ("request", "response"):
        actual = d["topology"][direction]
        want = config["topology"][direction]
        assert [x["name"] for x in actual["nodes"]] == sorted(
            x["name"] for x in want["nodes"]
        ), "NODES"
        assert actual["links"] == sorted(
            want["links"], key=lambda x: (x["from"], x["to"])
        ), "LINKS"
        for role in ("entries", "exits"):
            assert actual[role] == sorted(
                want[role], key=lambda x: x["endpoint"]
            ), "ATTACHMENTS"
        adj = {x["name"]: [] for x in want["nodes"]}
        for edge in want["links"]:
            adj[edge["from"]].append(edge["to"])
        hardware = {x["name"]: x["hardware_node"] for x in actual["nodes"]}
        routes = {}
        for entry in want["entries"]:
            pending = [(entry["node"], [entry["node"]])]
            paths = {}
            while pending:
                node, path = pending.pop()
                assert node not in paths, "UNIQUE_PATH"
                paths[node] = path
                pending.extend((child, path + [child]) for child in adj[node])
            for exit in want["exits"]:
                path = paths[exit["node"]]
                used.update(path)
                routes[entry["endpoint"], exit["endpoint"]] = [
                    hardware[x] for x in path
                ]
        got = {
            (x["entry"], x["exit"]): x["hardware_nodes"]
            for x in n[direction + "_routes"]
        }
        assert got == routes and len(got) == len(n[direction + "_routes"]), "ALL_ROUTES"
    assert used == {
        x["name"] for x in config["topology"]["request"]["nodes"]
    }, "ALL_NODES_USED"
    ports = mapping["ports"]
    assert len({p["name"] for p in ports}) == len(ports), "UNIQUE_PORTS"
    endpoints = {p["endpoint"] for p in ports}
    domains = [x["name"] for x in config["clock_domains"]]
    owner = {"initiator:" + x["name"]: x["clock_domain"] for x in config["initiators"]}
    owner.update({"target:" + x["name"]: x["clock_domain"] for x in config["targets"]})
    owner.update({"domain:" + x: x for x in domains})
    assert endpoints == {"reset:reset_n", "test:test"} | {"domain:" + x for x in domains} | {
        "initiator:" + s for s in sources
    } | {"target:" + t for t in targets}, "PORT_ENDPOINTS"
    declarations = {
        name: (direction, int(high) + 1 if high else 1)
        for direction, high, name in re.findall(
            r"\b(input|output)\s+(?:wire\s+)?(?:\[(\d+):0\]\s+)?([A-Za-z_][A-Za-z0-9_]*)",
            rtl,
        )
    }
    for p in ports:
        assert p["clock"] == (
            "" if p["signal"] in ("reset_n", "test") else "clk_" + owner[p["endpoint"]]), "CLOCK"
        assert declarations.get(p["name"]) == (p["direction"], p["width"]), "RTL_PORT"
        if p["signal"] in ("pwdata", "prdata", "wdata", "rdata"):
            assert p["width"] == 32, "DATA_WIDTH"
    assert d["contract"]["arbitration"]["default"] == "round_robin", "ARBITRATION"
    assert n["storage"] and n["resources"], "RESOURCE_BINDINGS"
    # Several domains: every node and endpoint sits in its configured domain, every domain is
    # used, and each crossing joins the domains of its two ends.
    cuts = 0
    if len(domains) > 1:
        cdc = n["cdc"]
        placed = {"source/" + x["name"]: x["clock_domain"] for x in config["initiators"]}
        placed.update({"target/" + x["name"]: x["clock_domain"] for x in config["targets"]})
        for direction, key in (("request", "req/"), ("response", "rsp/")):
            hardware = {x["name"]: x["hardware_node"] for x in d["topology"][direction]["nodes"]}
            placed.update({key + hardware[x["name"]]: x["clock_domain"]
                           for x in config["topology"][direction]["nodes"]})
        assert cdc["objects"] == placed and set(placed.values()) == set(domains), "DOMAINS"
        for cut in cdc["cuts"]:
            direction, edge = cut["segment"].split("/")
            ends = [direction + "/" + x for x in edge.split(">")]
            ends = [x if x in placed else ("source/" if x.split("/")[1] in sources else "target/")
                    + x.split("/")[1] for x in ends]
            assert (cut["from_domain"], cut["to_domain"]) == tuple(placed[x] for x in ends), "CUT"
            assert cut["from_domain"] != cut["to_domain"], "CUT_CROSSES"
        cuts = len(cdc["cuts"])
    assert {x["path"]: x["role"] for x in bundle["files"]} == {
        module + ".v": "rtl",
        module + ".map.json": "interface_map",
        module + ".dependency.json": "dependency_graph",
        module + ".bundle.json": "manifest",
        "nocloom_clock_gate.v": "cell_model",
        "nocloom_synchronizer.v": "cell_model",
    }, "ARTIFACTS"
    return dict(
        sources=len(sources),
        targets=len(targets),
        nodes=len(used),
        routes=len(sources) * len(targets) * 2,
        ports=len(ports),
        domains=len(domains),
        cuts=cuts,
    )
