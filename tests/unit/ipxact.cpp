// IP-XACT component: the other artifacts keep their bytes, the bundle lists the component once,
// bus interfaces use the public AMBA definitions, windows become address space segments and
// subspace maps of connected pairs, the bytes ignore declaration order, and bad input is rejected.
// Schema validation against IEEE 1685-2009 is the ipxact case of tests/run.py.
