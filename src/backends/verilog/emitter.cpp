using Pins = std::vector<std::pair<std::string, std::string>>;
// A generated cell file: header, optional include guard, module with its port list (inputs, then
// the output), body.
std::string cell_text(const std::string &title, const std::string &guard, const std::string &module,
                      const std::string &parameters, const std::vector<std::string> &inputs,
                      const std::string &output, const std::string &body) {
  std::string out =
      "// Generated by NocLoom\n" + output_license_comment("//") + "// " + title + "\n";
  if (!guard.empty())
    out += "`ifndef " + guard + "\n`define " + guard + "\n";
  out += "`default_nettype none\nmodule " + module + parameters + " (\n";
  for (const auto &pin : inputs)
    out += "  input wire " + pin + ",\n";
  out += "  output wire " + output + "\n);\n" + body + "endmodule\n`default_nettype wire\n";
  return out + (guard.empty() ? "" : "`endif\n");
}
// An instance of a bound library cell: its role pins, then its tied pins.
std::string bound(const std::string &module, const std::string &name, Pins pins,
                  const std::map<std::string, bool> &tie) {
  for (const auto &[pin, value] : tie)
    pins.emplace_back(pin, value ? "1'b1" : "1'b0");
  std::string out = module + " " + name + " (";
  for (std::size_t i = 0; i < pins.size(); ++i)
    out += (i ? ", ." : ".") + pins[i].first + "(" + pins[i].second + ")";
  return out + ");\n";
}
std::vector<std::string> input_pins(std::vector<std::string> roles,
                                    const std::map<std::string, bool> &tie) {
  std::ranges::transform(tie, std::back_inserter(roles), [](const auto &e) { return e.first; });
  return roles;
}
// Clock gate: while clock_in is low the latch follows enable | test, and clock_out is clock_in
// while the latch holds one, so clock_out only pulses for whole high phases of clock_in.
CellFile clock_gate_file(const std::optional<ClockGateCell> &cell) {
  const std::vector<std::string> ports{"clock_in", "enable", "test"};
  if (!cell)
    return {"nocloom_clock_gate.v",
            cell_text("Clock gate cell model.", "NOCLOOM_CLOCK_GATE_V", "nocloom_clock_gate", "",
                      ports, "clock_out",
                      "reg latched;\nalways @(clock_in or enable or test)\n  if (!clock_in)\n "
                      "   latched <= enable | test;\nassign clock_out = clock_in & latched;\n")};
  Pins pins{{cell->clock, "clock_in"}, {cell->enable, cell->test ? "enable" : "enable | test"}};
  if (cell->test)
    pins.emplace_back(*cell->test, "test");
  pins.emplace_back(cell->output, "clock_out");
  return {"nocloom_clock_gate.v",
          cell_text("Clock gate cell wrapper of " + cell->module + ".", "NOCLOOM_CLOCK_GATE_V",
                    "nocloom_clock_gate", "", ports, "clock_out",
                    bound(cell->module, "u_cell", pins, cell->tie))};
}
// The event control of a register on clock that a reset clears: the reset edge joins it unless
// the register clears synchronously.
std::string clocked(const std::string &clock, const std::string &reset, bool low, bool sync) {
  return "always @(posedge " + clock +
         (sync ? std::string{} : (low ? " or negedge " : " or posedge ") + reset) + ")";
}
// The synchronizer cell module; a synchronously clearing one has its own name.
std::string synchronizer_module(bool sync) {
  return sync ? "nocloom_synchronizer_sync_reset" : "nocloom_synchronizer";
}
// Synchronizer: STAGES registers cleared by reset_n shift d toward q. A bound flip-flop is
// chained STAGES times (u_stage[k].u_cell); an integrated synchronizer is the cell u_cell.
CellFile synchronizer_file(const std::optional<SynchronizerBinding> &cell, bool sync) {
  std::string body = "(* ASYNC_REG = \"TRUE\" *) reg [STAGES - 1:0] stage;\n" +
                     clocked("clock", "reset_n", true, sync) +
                     "\n  if (!reset_n)\n    stage <= {STAGES{1'b0}};\n  else\n    stage <= "
                     "{stage[STAGES - 2:0], d};\nassign q = stage[STAGES - 1];\n";
  if (cell) {
    const bool chained = cell->stages == 1;
    const Pins pins{{cell->clock, "clock"},
                    {cell->reset, cell->reset_active_low ? "reset_n" : "~reset_n"},
                    {cell->data, chained ? "chain[k]" : "d"},
                    {cell->output, chained ? "chain[k + 1]" : "q"}};
    body = chained ? "wire [STAGES:0] chain;\nassign chain[0] = d;\ngenvar k;\ngenerate\n  for "
                     "(k = 0; k < STAGES; k = k + 1) begin : u_stage\n    " +
                         bound(cell->module, "u_cell", pins, cell->tie) +
                         "  end\nendgenerate\nassign q = chain[STAGES];\n"
                   : bound(cell->module, "u_cell", pins, cell->tie);
  }
  const auto module = synchronizer_module(sync);
  return {module + ".v",
          cell_text(cell ? "Synchronizer cell wrapper of " + cell->module + "."
                         : "Synchronizer cell model.",
                    sync ? "NOCLOOM_SYNCHRONIZER_SYNC_RESET_V" : "NOCLOOM_SYNCHRONIZER_V", module,
                    " #(\n  parameter STAGES = 2\n)", {"clock", "reset_n", "d"}, "q", body)};
}
// Behavioral models of the bound library cells, from their role pins alone.
std::string model_title(const std::string &module) {
  return "Behavioral model of library cell " + module + " as bound; not for synthesis.";
}
CellFile model(const ClockGateCell &cell) {
  const auto test = cell.test.value_or("");
  const auto roles = test.empty() ? std::vector{cell.clock, cell.enable}
                                  : std::vector{cell.clock, cell.enable, test};
  return {cell.module + ".v",
          cell_text(model_title(cell.module), "", cell.module, "", input_pins(roles, cell.tie),
                    cell.output,
                    "reg latched;\nalways @(" + cell.clock + " or " + cell.enable +
                        (test.empty() ? "" : " or " + test) + ")\n  if (!" + cell.clock +
                        ")\n    latched <= " + cell.enable + (test.empty() ? "" : " | " + test) +
                        ";\nassign " + cell.output + " = " + cell.clock + " & latched;\n"),
          true};
}
CellFile model(const SynchronizerBinding &cell, bool sync) {
  const auto n = decimal(cell.stages);
  const bool low = cell.reset_active_low;
  return {cell.module + ".v",
          cell_text(model_title(cell.module), "", cell.module, "",
                    input_pins({cell.clock, cell.data, cell.reset}, cell.tie), cell.output,
                    "reg [" + n + " - 1:0] stage;\n" + clocked(cell.clock, cell.reset, low, sync) +
                        "\n  if (" + (low ? "!" : "") + cell.reset + ")\n    stage <= " + n +
                        "'d0;\n  else\n    stage <= " +
                        (cell.stages == 1
                             ? cell.data
                             : "{stage[" + decimal(cell.stages - 2) + ":0], " + cell.data + "}") +
                        ";\nassign " + cell.output + " = stage[" + n + " - 1];\n"),
          true};
}
