std::string SynchronizerChain::instance(unsigned bit) const {
  return "nl_internal_v" + decimal(head) + "_sync" + (width > 1 ? decimal(bit) : "");
}
// Each chain follows, from its head, the stage that samples the last one. Every stage belongs to
// one chain of two or more stages on one clock and reset, clearing to zero.
std::vector<SynchronizerChain> synchronizer_chains(const HardwareIR &ir) {
  const auto count = ir.emitted.value_or(ir.values.size());
  auto state = [&](std::size_t i) -> const State & {
    return ir.states.at(ir.values.at(i).state.index);
  };
  std::set<std::size_t> stages;
  std::map<std::size_t, std::size_t> sampled_by;
  for (auto id : ir.synchronizer_stages)
    if (id.index < count)
      stages.insert(id.index);
  // A stage continues the chain of the stage it samples on the same clock and reset; a stage
  // sampling anything else heads a chain.
  auto continues = [&](std::size_t i) {
    const auto &s = state(i);
    return stages.contains(s.next.index) && s.clock.index == state(s.next.index).clock.index &&
           s.reset->signal.index == state(s.next.index).reset->signal.index;
  };
  for (auto i : stages)
    if (!state(i).reset || state(i).reset->value != 0)
      throw std::logic_error("A synchronizer stage is not cleared by a reset");
  for (auto i : stages)
    if (continues(i) && !sampled_by.emplace(state(i).next.index, i).second)
      throw std::logic_error("Two synchronizer stages sample one stage");
  std::vector<SynchronizerChain> chains;
  std::size_t covered = 0;
  for (auto head : stages) {
    if (continues(head))
      continue;
    const auto &first = state(head);
    SynchronizerChain c{
        head, head, 1, ir.values[head].width, first.next, first.clock, first.reset->signal};
    for (auto it = sampled_by.find(head); it != sampled_by.end(); it = sampled_by.find(c.tail)) {
      c.tail = it->second;
      ++c.stages;
    }
    if (c.stages < 2)
      throw std::logic_error("A synchronizer chain has one stage");
    covered += c.stages;
    chains.push_back(c);
  }
  if (covered != stages.size())
    throw std::logic_error("A synchronizer stage is in no chain");
  return chains;
}
std::vector<CellFile> cell_files(const HardwareIR &ir, const TechnologyCells &cells) {
  const auto count = ir.emitted.value_or(ir.values.size());
  const bool gates =
      std::any_of(ir.values.begin(), ir.values.begin() + static_cast<std::ptrdiff_t>(count),
                  [](const Value &v) { return v.op == Op::ClockGate; });
  const bool synchronizers = !synchronizer_chains(ir).empty();
  std::vector<CellFile> out;
  if (gates)
    out.push_back(clock_gate_file(cells.clock_gate));
  if (synchronizers)
    out.push_back(synchronizer_file(cells.synchronizer, ir.synchronous_reset));
  if (gates && cells.clock_gate)
    out.push_back(model(*cells.clock_gate));
  if (synchronizers && cells.synchronizer)
    out.push_back(model(*cells.synchronizer, ir.synchronous_reset));
  return out;
}
std::string emit_verilog(const HardwareIR &ir) {
  auto width = [](unsigned bits) {
    return bits == 1 ? std::string{} : "[" + decimal(bits - 1) + ":0] ";
  };
  auto name = [](std::size_t id) { return "nl_internal_v" + decimal(id); };
  std::string out = "// Generated by NocLoom\n" + output_license_comment("//") +
                    "`default_nettype none\nmodule " + ir.name + " (\n";
  for (std::size_t i = 0; i < ir.ports.size(); ++i) {
    const auto &port = ir.ports[i];
    out += std::string("  ") + (port.input ? "input wire " : "output wire ") + width(port.width) +
           port.name;
    out += i + 1 == ir.ports.size() ? "\n);\n" : ",\n";
  }
  // Synchronizer chains are cell instances: their stages are no registers here, and the last
  // stage of each is a net driven by the instances.
  std::map<std::size_t, SynchronizerChain> tails;
  std::set<std::size_t> synchronized;
  for (const auto &c : synchronizer_chains(ir)) {
    tails.emplace(c.tail, c);
    for (auto i = c.tail; i != c.head; i = ir.states[ir.values[i].state.index].next.index)
      synchronized.insert(i);
    synchronized.insert(c.head);
  }
  // A canonical IR keeps logic the outputs never observe after its emitted
  // prefix (see canonicalize); that logic is not hardware.
  const auto count = ir.emitted.value_or(ir.values.size());
  for (std::size_t i = 0; i < count; ++i)
    if (!synchronized.contains(i) || tails.contains(i))
      out += std::string(ir.values[i].op == Op::State && !tails.contains(i) ? "reg " : "wire ") +
             width(ir.values[i].width) + name(i) + ";\n";
  for (std::size_t i = 0; i < count; ++i) {
    const auto &v = ir.values[i];
    auto arg = [&](unsigned n) { return name(v.operands[n].index); };
    std::string expression;
    switch (v.op) {
    case Op::State:
      if (const auto chain = tails.find(i); chain != tails.end()) {
        const auto &c = chain->second;
        auto bit = [&](std::size_t value, unsigned b) {
          return name(value) + (c.width > 1 ? "[" + decimal(b) + "]" : "");
        };
        for (unsigned b = 0; b < c.width; ++b)
          out += synchronizer_module(ir.synchronous_reset) + " #(.STAGES(" + decimal(c.stages) +
                 ")) " + c.instance(b) + " (.clock(" + name(c.clock.index) + "), .reset_n(" +
                 name(c.reset.index) + "), .d(" + bit(c.source.index, b) + "), .q(" + bit(i, b) +
                 "));\n";
      }
      continue;
    case Op::Input:
      expression = ir.ports.at(v.input_port.index).name;
      break;
    case Op::Constant:
      expression = decimal(v.width) + "'d" + decimal(v.literal);
      break;
    case Op::ZeroExtend:
      expression =
          "{" + decimal(v.width - ir.values.at(v.operands[0].index).width) + "'d0, " + arg(0) + "}";
      break;
    case Op::UnsignedLess:
      expression = "(" + arg(0) + " < " + arg(1) + ")";
      break;
    case Op::Equal:
      expression = "(" + arg(0) + " == " + arg(1) + ")";
      break;
    case Op::BitNot:
      expression = "(~" + arg(0) + ")";
      break;
    case Op::BitAnd:
      expression = "(" + arg(0) + " & " + arg(1) + ")";
      break;
    case Op::BitOr:
      expression = "(" + arg(0) + " | " + arg(1) + ")";
      break;
    case Op::Subtract:
      expression = "(" + arg(0) + " - " + arg(1) + ")";
      break;
    case Op::Slice: {
      // The offset operand is a verified constant: emit a constant part-select.
      const auto at = ir.values.at(v.operands[1].index).literal;
      // A one-bit net has no part to select (IEEE 1364-2001 5.2.1: vectors only).
      expression = ir.values.at(v.operands[0].index).width == 1
                       ? arg(0)
                       : arg(0) + "[" + decimal(at + v.width - 1) + ":" + decimal(at) + "]";
      break;
    }
    case Op::Concat:
      expression = "{" + arg(0) + ", " + arg(1) + "}";
      break;
    case Op::Select:
      expression = "(" + arg(0) + " ? " + arg(1) + " : " + arg(2) + ")";
      break;
    case Op::ClockGate:
      out += "nocloom_clock_gate " + name(i) + "_gate (.clock_in(" + arg(0) + "), .enable(" +
             arg(1) + "), .test(" + arg(2) + "), .clock_out(" + name(i) + "));\n";
      continue;
    default:
      throw std::logic_error("Unverified hardware operation");
    }
    out += "assign " + name(i) + " = " + expression + ";\n";
  }
  for (const auto &driver : ir.drivers)
    out +=
        "assign " + ir.ports.at(driver.port.index).name + " = " + name(driver.value.index) + ";\n";
  std::map<std::pair<std::size_t, std::size_t>, std::vector<State>> groups;
  std::map<std::size_t, std::vector<State>> held_groups;
  for (const auto &state : ir.states) {
    if (state.output.index >= count || synchronized.contains(state.output.index))
      continue;
    if (state.reset)
      groups[{state.clock.index, state.reset->signal.index}].push_back(state);
    else
      held_groups[state.clock.index].push_back(state);
  }
  for (const auto &[key, states] : groups) {
    const auto &domain = states.front();
    const auto reset = name(domain.reset->signal.index);
    out += clocked(name(domain.clock.index), reset, true, ir.synchronous_reset) +
           " begin\n  if (!" + reset + ") begin\n";
    for (const auto &state : states)
      out += "    " + name(state.output.index) +
             " <= " + decimal(ir.values[state.output.index].width) + "'d" +
             decimal(state.reset->value) + ";\n";
    out += "  end else begin\n";
    for (const auto &state : states)
      out += "    " + name(state.output.index) + " <= " + name(state.next.index) + ";\n";
    out += "  end\nend\n";
  }
  for (const auto &[clock, states] : held_groups) {
    out += "always @(posedge " + name(clock) + ") begin\n";
    for (const auto &state : states)
      out += "  " + name(state.output.index) + " <= " + name(state.next.index) + ";\n";
    out += "end\n";
  }
  return out + "endmodule\n`default_nettype wire\n";
}
